// Regenerates builders/schemas/*.json: the option schemas of the wrapper builders, from the stock @angular/build builders.
//
// The Angular CLI reads a builder's schema to parse command-line flags (`ng build --output-path x`, `ng serve --port 4300`) and to
// validate and default the target's options, so a wrapper builder needs the stock schema. One copy serves Angular 20, 21 and 22:
//  - application, dev-server, karma, extract-i18n (identical in the three majors): the union of the properties at every depth (scripts/schema-union.mjs); a property that is not in
//    every major, or whose default differs, has no default in the copy (a default of one major would be filled for the others);
//  - unit-test: the majors differ (`runner` is required in 20, defaults of `include`/`exclude` differ, many options are new), so the
//    union is taken WITHOUT defaults and without `required`: the wrapper only passes options on, and the stock builder that runs
//    validates them against its own schema and applies its own defaults.
//
// usage: node scripts/sync-builder-schemas.mjs [<dir with v20/ v21/ v22/ extracted by `npm pack @angular/build@<major>`>]
// Without an argument the three packages are fetched with `npm pack` (network needed).
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ACCEPTED, unionOf } from './schema-union.mjs';

const MAJORS = [20, 21, 22];
const BUILDERS = { application: 'application', 'dev-server': 'dev-server', 'unit-test': 'unit-test', karma: 'karma', 'extract-i18n': 'extract-i18n' };
const out = fileURLToPath(new URL('../builders/schemas/', import.meta.url));

let source = process.argv[2];
if (!source) {
  source = mkdtempSync(join(tmpdir(), 'ng-build-schemas-'));
  for (const major of MAJORS) {
    const dir = join(source, `v${major}`);
    mkdirSync(dir, { recursive: true });
    const version = execFileSync('npm', ['view', `@angular/build@${major}`, 'version'], { encoding: 'utf8' }).trim().split('\n').pop().split(' ').pop().replace(/'/g, '');
    execFileSync('npm', ['pack', `@angular/build@${version}`, '--silent'], { cwd: dir, stdio: 'ignore' });
    execFileSync('sh', ['-c', 'tar -xzf angular-build-*.tgz package/src package/package.json'], { cwd: dir });
  }
}
const load = (major, builder) => JSON.parse(readFileSync(join(source, `v${major}`, 'package/src/builders', builder, 'schema.json'), 'utf8'));
const versionOf = (major) => JSON.parse(readFileSync(join(source, `v${major}`, 'package/package.json'), 'utf8')).version;

mkdirSync(out, { recursive: true });
for (const [name, dir] of Object.entries(BUILDERS)) {
  const newest = unionOf(MAJORS.map((major) => load(major, dir)), { noDefaults: name === 'unit-test', accept: ACCEPTED[name] });
  newest.$id = `TypeGpuAngular${name.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase())}`;
  newest.title = `TypeGPU wrapper of the Angular ${name} builder`;
  newest.$comment = `Generated by scripts/sync-builder-schemas.mjs from @angular/build ${MAJORS.map(versionOf).join(', ')}. Do not edit.`;
  writeFileSync(join(out, `${name}.json`), JSON.stringify(newest, null, 2) + '\n');
  console.log(`${name}: ${Object.keys(newest.properties).length} properties${name === 'unit-test' ? ' (no defaults, nothing required)' : ''}`);
}
