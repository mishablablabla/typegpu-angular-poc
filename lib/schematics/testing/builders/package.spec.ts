// What the package declares for the Angular CLI: builders.json, the option schemas, and what ng-packagr must ship.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

const LIB = join(__dirname, '..', '..', '..');
const json = (path: string) => JSON.parse(readFileSync(join(LIB, path), 'utf8'));
const NAMES = ['application', 'dev-server', 'unit-test', 'karma'];

describe('builders.json', () => {
  const manifest = json('builders.json');

  it('is the package\'s `builders` entry and declares exactly the four wrappers, each with an implementation and a schema that exist', () => {
    expect(json('package.json').builders).toBe('./builders.json');
    expect(Object.keys(manifest.builders).sort()).toEqual([...NAMES].sort());
    for (const [name, builder] of Object.entries<any>(manifest.builders)) {
      expect(existsSync(join(LIB, builder.implementation)), `${name} implementation`).toBe(true);
      expect(existsSync(join(LIB, builder.schema)), `${name} schema`).toBe(true);
      expect(builder.implementation.endsWith('.cjs')).toBe(true); // Architect loads builders with require()
    }
  });

  it('ng-packagr ships them: the builders folder and builders.json are assets, jsonc-parser is an allowed dependency', () => {
    const ngPackage = json('ng-package.json');
    expect(ngPackage.assets).toEqual(expect.arrayContaining([{ input: 'builders', glob: '**/*', output: 'builders' }, { input: '.', glob: 'builders.json', output: '.' }]));
    expect(ngPackage.allowedNonPeerDependencies).toContain('jsonc-parser');
  });

  it('declares the Architect it needs as an optional peer (pnpm links peers, not undeclared packages)', () => {
    const manifestJson = json('package.json');
    expect(manifestJson.peerDependencies['@angular-devkit/architect']).toBeDefined();
    expect(manifestJson.peerDependenciesMeta['@angular-devkit/architect']).toEqual({ optional: true });
  });
});

describe('the option schemas (generated by scripts/sync-builder-schemas.mjs)', () => {
  it.each(NAMES)('%s: a closed object schema whose every $ref resolves, marked as generated', (name) => {
    const schema = json(`builders/schemas/${name}.json`);
    expect(schema.type).toBe('object');
    expect(schema.additionalProperties).toBe(false);
    expect(schema.$comment).toMatch(/Generated by scripts\/sync-builder-schemas\.mjs from @angular\/build 20\.\d+\.\d+, 21\.\d+\.\d+, 22\.\d+\.\d+/);
    const refs = [...new Set(JSON.stringify(schema).match(/#\/definitions\/[A-Za-z0-9_-]+/g) ?? [])];
    for (const ref of refs) expect(schema.definitions?.[ref.split('/').pop()!], ref).toBeDefined();
  });

  it('application, dev-server and karma keep the official defaults and required options (identical in Angular 20, 21 and 22)', () => {
    expect(json('builders/schemas/application.json').required).toEqual(['tsConfig']);
    expect(json('builders/schemas/application.json').properties.outputHashing.default).toBe('none');
    expect(json('builders/schemas/dev-server.json').required).toEqual(['buildTarget']);
    expect(json('builders/schemas/dev-server.json').properties.define).toBeDefined(); // Angular 21+: the union has it
    expect(json('builders/schemas/karma.json').required).toEqual(['tsConfig']);
  });

  it('unit-test is the union of the three majors WITHOUT defaults and required options (they differ between majors; the official builder applies its own)', () => {
    const schema = json('builders/schemas/unit-test.json');
    expect(schema.required).toBeUndefined();
    expect(JSON.stringify(schema).includes('"default":')).toBe(false);
    for (const option of ['runner', 'codeCoverage', 'coverage', 'isolate', 'include']) expect(schema.properties[option], option).toBeDefined(); // Angular 20 only, 21+, 22 only, all
  });
});
